CREATE TABLE dining_table (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number           integer     NOT NULL,
    qr_token         varchar(64) NOT NULL,
    pin              char(4)     NOT NULL,
    active           boolean     NOT NULL DEFAULT true,
    token_rotated_at timestamptz NOT NULL,
    created_at       timestamptz NOT NULL,
    CONSTRAINT uk_dining_table_number UNIQUE (number),
    CONSTRAINT uk_dining_table_qr_token UNIQUE (qr_token),
    CONSTRAINT ck_dining_table_number CHECK (number > 0),
    CONSTRAINT ck_dining_table_pin CHECK (pin ~ '^[0-9]{4}$')
);
