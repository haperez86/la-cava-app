CREATE TABLE notification (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint       NOT NULL REFERENCES app_user (id),
    type         varchar(16)  NOT NULL,
    order_id     bigint       NOT NULL REFERENCES customer_order (id),
    table_number integer      NOT NULL,
    message      varchar(160) NOT NULL,
    created_at   timestamptz  NOT NULL,
    read_at      timestamptz,
    CONSTRAINT ck_notification_type CHECK (type IN ('ORDER_READY', 'ORDER_CREATED'))
);
CREATE INDEX ix_notification_unread ON notification (user_id) WHERE read_at IS NULL;
CREATE INDEX ix_notification_order ON notification (order_id);
