-- LCV-HU-10: pedidos, ítems y lotes consumidos por cada ítem (docs/02-modelo-datos.md, D10, D11, D38).
-- bill_id queda sin FK: la tabla bill llega en la Épica 6, cuya migración agregará la restricción.

CREATE TABLE customer_order (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id      bigint       NOT NULL REFERENCES dining_table (id),
    waiter_id     bigint       NOT NULL REFERENCES app_user (id),
    created_by    bigint       NOT NULL REFERENCES app_user (id),
    status        varchar(16)  NOT NULL,
    note          varchar(140),
    created_at    timestamptz  NOT NULL,
    started_at    timestamptz,
    ready_at      timestamptz,
    delivered_at  timestamptz,
    closed_at     timestamptz,
    cancelled_at  timestamptz,
    cancel_reason varchar(120),
    bill_id       bigint,
    version       bigint       NOT NULL DEFAULT 0,
    CONSTRAINT ck_customer_order_status CHECK (status IN ('PENDING', 'IN_PREPARATION', 'READY', 'DELIVERED',
        'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_customer_order_cancel_reason CHECK (status <> 'CANCELLED'
        OR (cancel_reason IS NOT NULL AND cancelled_at IS NOT NULL))
);
CREATE INDEX ix_customer_order_open_table ON customer_order (table_id)
    WHERE status IN ('PENDING', 'IN_PREPARATION', 'READY', 'DELIVERED');
CREATE INDEX ix_customer_order_waiter_status ON customer_order (waiter_id, status);
CREATE INDEX ix_customer_order_status_created ON customer_order (status, created_at);

CREATE TABLE order_item (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint        NOT NULL REFERENCES customer_order (id),
    product_id   bigint        NOT NULL REFERENCES product (id),
    product_name varchar(60)   NOT NULL,
    unit_price   numeric(14,2) NOT NULL,
    quantity     integer       NOT NULL,
    note         varchar(80),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_item_unit_price CHECK (unit_price > 0)
);
CREATE INDEX ix_order_item_order ON order_item (order_id);

CREATE TABLE order_item_lot (
    order_item_id bigint  NOT NULL REFERENCES order_item (id),
    lot_id        bigint  NOT NULL REFERENCES stock_lot (id),
    quantity      integer NOT NULL,
    CONSTRAINT pk_order_item_lot PRIMARY KEY (order_item_id, lot_id),
    CONSTRAINT ck_order_item_lot_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_order_item_lot_lot ON order_item_lot (lot_id);

-- stock_movement.order_id (V3) sigue sin FK, como en docs/02; solo se indexa para buscar los movimientos de un pedido.
CREATE INDEX ix_stock_movement_order ON stock_movement (order_id);
