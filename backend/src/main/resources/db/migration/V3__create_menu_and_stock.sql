-- stock_lot y stock_movement se crean ahora para el lote inicial (CA4); la Épica 2 los amplía.

CREATE TABLE category (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(40) NOT NULL
);
CREATE UNIQUE INDEX uk_category_name_lower ON category (lower(name));

CREATE TABLE product (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(60)   NOT NULL,
    category_id  bigint        NOT NULL REFERENCES category (id),
    price        numeric(14,2) NOT NULL,
    description  varchar(120),
    icon         varchar(16),
    min_stock    integer       NOT NULL DEFAULT 0,
    active       boolean       NOT NULL DEFAULT true,
    season_name  varchar(40),
    season_until date,
    created_at   timestamptz   NOT NULL,
    updated_at   timestamptz   NOT NULL,
    CONSTRAINT ck_product_price CHECK (price > 0),
    CONSTRAINT ck_product_min_stock CHECK (min_stock >= 0),
    CONSTRAINT ck_product_season_until CHECK (season_name IS NULL OR season_until IS NOT NULL)
);
CREATE UNIQUE INDEX uk_product_name_lower ON product (lower(name));
CREATE INDEX ix_product_category ON product (category_id);

CREATE TABLE stock_lot (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         bigint      NOT NULL REFERENCES product (id),
    quantity_received  integer     NOT NULL,
    quantity_available integer     NOT NULL,
    expires_on         date        NOT NULL,
    season_name        varchar(40),
    received_at        timestamptz NOT NULL,
    created_by         bigint      NOT NULL REFERENCES app_user (id),
    version            bigint      NOT NULL DEFAULT 0,
    CONSTRAINT ck_stock_lot_received CHECK (quantity_received > 0),
    CONSTRAINT ck_stock_lot_available CHECK (quantity_available >= 0 AND quantity_available <= quantity_received)
);
CREATE INDEX ix_stock_lot_product_expires ON stock_lot (product_id, expires_on);
CREATE INDEX ix_stock_lot_expires ON stock_lot (expires_on);

CREATE TABLE stock_movement (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint      NOT NULL REFERENCES product (id),
    lot_id     bigint      REFERENCES stock_lot (id),
    type       varchar(24) NOT NULL,
    quantity   integer     NOT NULL,
    note       varchar(140),
    order_id   bigint,
    user_id    bigint      NOT NULL REFERENCES app_user (id),
    created_at timestamptz NOT NULL,
    CONSTRAINT ck_stock_movement_type CHECK (type IN ('LOT_IN', 'SALE', 'ORDER_CANCEL_RETURN', 'WASTE_OUT',
        'DAMAGED_OUT', 'INTERNAL_USE_OUT', 'ADJUSTMENT_OUT', 'EXPIRED_WRITE_OFF')),
    CONSTRAINT ck_stock_movement_quantity CHECK (quantity <> 0)
);
CREATE INDEX ix_stock_movement_product ON stock_movement (product_id, created_at);
CREATE INDEX ix_stock_movement_lot ON stock_movement (lot_id);
